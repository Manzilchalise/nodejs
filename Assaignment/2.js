let x=10
   let y=20
   let z="+"
   switch(z){
    case '-':
        console.log(x-y)
        break
    case '+':
        console.log(x+y)
        break
    case '/':
        console.log(x/y)
        break
    case '*':
        console.log(x*y)
        break
    case '%':
        console.log(x%y)
        break
    default:
        console.log("Invalid")
   }